#!/usr/bin/env bash
# Builds AES-CORE.md by concatenating the chapters of standard/ in order.
# Usage: ./scripts/build-core.sh          (writes AES-CORE.md)
#        ./scripts/build-core.sh --check  (fails if AES-CORE.md is out of date)
set -euo pipefail
cd "$(dirname "$0")/.."

# "**Version:**" (or "**Versión:**" in READMEs before 2.0.0).
version=$(sed -nE 's/^\*\*Versi(o|ó)n:\*\* *([0-9.]+).*/\2/p' README.md | head -n1)
[[ -n "$version" ]] || { echo "Version not found in README.md" >&2; exit 1; }

tmp=$(mktemp)
{
  printf '# Agentic Engineering Standard — AES Core %s\n\n' "$version"
  printf '<!-- Generated by scripts/build-core.sh from standard/. Do not edit by hand. -->\n\n'
  first=1
  for f in standard/[0-9][0-9]-*.md; do
    if [[ $first -eq 0 ]]; then printf '\n---\n\n'; fi
    first=0
    tr -d '\r' < "$f"
  done
} > "$tmp"

if [[ "${1:-}" == "--check" ]]; then
  # Ignoring CR: a Windows checkout with core.autocrlf has CRLF in standard/ and in AES-CORE.md.
  if ! diff -q <(tr -d '\r' < "$tmp") <(tr -d '\r' < AES-CORE.md 2>/dev/null) >/dev/null 2>&1; then
    echo "AES-CORE.md is out of date. Run ./scripts/build-core.sh" >&2
    rm -f "$tmp"; exit 1
  fi
  rm -f "$tmp"; echo "AES-CORE.md is up to date."
else
  mv "$tmp" AES-CORE.md
  echo "AES-CORE.md built (AES $version)."
fi
